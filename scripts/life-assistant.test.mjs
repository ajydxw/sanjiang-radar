import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import { resolve, relative, isAbsolute, sep } from 'node:path';
import { chromium } from 'playwright-core';
import { createRadarServer } from './serve-radar.mjs';
import { createAssistantStore } from './assistant-questions.mjs';
import { publishReviewedBatch } from './assistant-queue.mjs';
import { POLITICAL_TOPIC_MESSAGE } from '../sources/question-policy.mjs';

test('生活助手同源提交、私有答复、通知背景与离线草稿真实可用，保留四项导航', async () => {
  const privateRoot = resolve('.sites-runtime');
  await mkdir(privateRoot, { recursive: true });
  const directory = await mkdtemp(resolve(privateRoot, 'assistant-browser-test-'));
  const store = await createAssistantStore({ directory, limits: { burst: 20 } });
  const server = await createRadarServer({ log: () => {}, assistantStore: store });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const assistantKey = 'sanjiang-radar-assistant-v1';
  const existingKey = 'sanjiang-radar-demo-v1';
  const existing = { favorites: ['test-notice'], profile: { college: '建筑学院', major: '建筑学', interests: [] } };
  let browser;
  try {
    const template = JSON.parse(await readFile('public/data/sanjiang-web.json', 'utf8')).items[0];
    const now = new Date().toISOString();
    const notice = { ...template, id: 'test-notice', title: '隔离测试校园通知', category: '学校通知', sourceType: 'school', sourcePortal: 'https://www.sju.edu.cn/', summary: '仅用于隔离浏览器检查。', publishedAt: now, registrationDeadline: '2099-12-31', eventEnd: undefined, freshmanAllowed: 'allowed', colleges: [], importance: 'high' };
    const feed = { schemaVersion: 1, generatedAt: now, items: [], sources: [{ id: 'test', name: '隔离测试来源', url: 'https://www.sju.edu.cn/', state: 'ok', count: 0, lastSuccessAt: now }] };
    const configure = context => context.route('**/data/*.json', route => route.fulfill({ json: { ...feed, items: route.request().url().endsWith('/sanjiang-web.json') ? [notice] : [] } }));
    browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true,
      storageState: { cookies: [], origins: [{ origin, localStorage: [{ name: existingKey, value: JSON.stringify(existing) }] }] } });
    await configure(context);
    await context.addInitScript(() => { Object.defineProperty(globalThis.crypto, 'randomUUID', { value: undefined }); });
    const page = await context.newPage();
    const errors = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push({ method: request.method(), url: request.url() }));
    await page.goto(origin, { waitUntil: 'networkidle' });
    await page.locator('.assistant-entry').click();
    await page.getByRole('heading', { name: '生活助手', exact: true }).waitFor();
    assert.equal(new URL(page.url()).hash, '#assistant');
    await page.getByText('非实时 · 由站长整理', { exact: true }).waitFor();
    const nav = page.getByRole('navigation', { name: '手机主导航' });
    assert.equal(await nav.locator('button').count(), 4);
    assert.equal(await nav.locator('[aria-current="page"]').count(), 0, '独立页面不伪装成今日雷达');
    const input = page.getByLabel('你想了解什么？');
    const save = page.getByRole('button', { name: '提交问题', exact: true });
    assert.equal(await save.isDisabled(), true);
    await page.getByRole('button', { name: '学习安排', exact: true }).click();
    assert.match(await input.inputValue(), /安排/);
    assert.equal(await page.locator('.assistant-record').count(), 0, '快捷问题只预填，不自动保存或回答');
    await input.fill('问'.repeat(501));
    assert.equal(await save.isDisabled(), true);
    await input.fill('你如何评价美国总统？');
    await save.click();
    assert.equal(await page.locator('.assistant-feedback').innerText(), POLITICAL_TOPIC_MESSAGE);
    assert.equal(requests.filter(request => request.method === 'POST').length, 0);
    assert.equal(await page.locator('.assistant-record').count(), 0);
    await page.route(`${origin}/api/assistant/questions`, route => route.fulfill({ status: 422, json: { error: POLITICAL_TOPIC_MESSAGE } }), { times: 1 });
    await input.fill('为什么天空是蓝色的？');
    await Promise.all([page.waitForResponse(response => response.url() === `${origin}/api/assistant/questions` && response.status() === 422), save.click()]);
    await page.getByText(POLITICAL_TOPIC_MESSAGE, { exact: true }).waitFor();
    assert.equal(await page.locator('.assistant-record').count(), 0, '服务器范围拒绝不能保存为已送达或离线草稿');
    assert.equal(await page.evaluate(key => localStorage.getItem(key), assistantKey), null);
    const lifeQuestion = '大一课程突然很多，应该怎么安排学习和休息？';
    await input.fill(lifeQuestion);
    await save.click();
    await page.getByText('问题已送达，等待整理回复。稍后可在这里刷新答复。', { exact: true }).waitFor();
    const receipt = JSON.parse(await page.evaluate(key => localStorage.getItem(key), assistantKey)).questions[0];
    assert.ok(receipt.accessToken && receipt.accessToken.length === 43);
    // This general answer was exercised with native GPT-6.1 Sol/high and separately reviewed in the owner chat.
    const lifeAnswer = '先把课程、作业截止时间和休息时间放进每周安排，每天选出最重要的两三件事。课后及时做简短复习，任务多时拆成小块，中间留些休息和缓冲。尽量保持规律睡眠，别长期靠熬夜赶进度；如果持续跟不上，可以向任课老师或辅导员求助。';
    await publishReviewedBatch(store, [{ id: receipt.id, status: 'answered', answer: lifeAnswer, sources: [], model: 'gpt-6.1-sol', reasoningEffort: 'high', review: { scope: true, facts: true, timing: true, fields: true, privacy: true } }]);
    await page.getByRole('button', { name: '刷新答复', exact: true }).click();
    await page.getByText(lifeAnswer, { exact: true }).waitFor();
    assert.equal((await fetch(`${origin}/api/assistant/questions/${receipt.id}`)).status, 404, '无自己的凭据无法读私有问题');
    assert.equal((await fetch(`${origin}/api/assistant/questions`)).status, 404, '没有公开列出全部提问的接口');
    assert.equal(await page.locator('.assistant-page').getByText(receipt.accessToken, { exact: false }).count(), 0);
    const question = '<img src=x onerror=alert(1)>\n<script>globalThis.executed=true</script>';
    await input.fill(question);
    await save.click();
    await page.getByRole('button', { name: '提交问题', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelectorAll('.assistant-record').length === 2);
    assert.match(await page.locator('.assistant-feedback').innerText(), /已送达/);
    assert.equal(await page.locator('.assistant-record img, .assistant-record script').count(), 0);
    assert.equal(await page.evaluate(() => globalThis.executed), undefined);
    assert.equal(await page.locator('.assistant-record-question').first().innerText(), question);
    assert.deepEqual(JSON.parse(await page.evaluate(key => localStorage.getItem(key), existingKey)), existing);
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.locator('.assistant-record').count(), 2);
    assert.equal(await page.locator('.assistant-record-question').first().innerText(), question);
    await page.getByText(lifeAnswer, { exact: true }).waitFor();
    const guide = page.locator('.assistant-guide').first();
    await guide.locator('summary').click();
    assert.ok(await guide.getAttribute('open') !== null);
    assert.match(await page.locator('.assistant-guide-note').innerText(), /不是.*AI 回答/);
    for (const width of [320, 390, 768, 1366]) {
      await page.setViewportSize({ width, height: 844 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `宽度 ${width} 无横向溢出`);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '返回雷达', exact: true }).click();
    await page.locator('.card-main').first().click();
    await page.getByRole('dialog').getByRole('button', { name: /问这条通知/ }).click();
    await page.getByRole('complementary', { name: '关于这条通知' }).waitFor();
    assert.match(await page.locator('.assistant-context').innerText(), /隔离测试校园通知/);
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.evaluate(() => document.body.style.overflow), '');
    await page.getByText('非实时 · 由站长整理', { exact: true }).waitFor();
    await input.fill('今年三江学院普通话考试到底哪一天开始报名？');
    await save.click();
    await page.waitForFunction(() => document.querySelectorAll('.assistant-record').length === 3);
    assert.match(await page.locator('.assistant-record-context').innerText(), /隔离测试校园通知/);
    const stored = JSON.parse(await page.evaluate(key => localStorage.getItem(key), assistantKey));
    assert.equal(stored.questions[0].contextId, 'test-notice');
    assert.equal(stored.questions[0].sourcePortal, undefined);
    assert.equal(stored.questions[0].answer, undefined);
    const unconfirmed = '暂无法确认三江学院2026年普通话考试的报名开始日期，目前没有当期官方通知可供核对。请以学校当期官方通知为准；你可以贴出通知原文，我帮你找出报名开始时间。';
    await publishReviewedBatch(store, [{ id: stored.questions[0].id, status: 'unconfirmed', answer: unconfirmed, sources: [], model: 'gpt-6.1-sol', reasoningEffort: 'high', review: { scope: true, facts: true, timing: true, fields: true, privacy: true } }]);
    await page.getByRole('button', { name: '刷新答复', exact: true }).click();
    await page.getByText(unconfirmed, { exact: true }).waitFor();
    await page.getByRole('button', { name: '移除通知背景', exact: true }).click();
    assert.equal(await page.locator('.assistant-context').count(), 0);
    await page.getByRole('button', { name: '清空本机记录', exact: true }).click();
    assert.equal(await page.locator('.assistant-record').count(), 0);
    assert.equal(await page.evaluate(key => localStorage.getItem(key), assistantKey), null);
    assert.deepEqual(JSON.parse(await page.evaluate(key => localStorage.getItem(key), existingKey)), existing);
    assert.equal(requests.filter(request => request.method === 'POST').length, 4, '包含一次服务器范围拒绝，每次明确提交只发送一次同源请求');
    assert.ok(requests.every(request => new URL(request.url).origin === origin), '没有模型或第三方请求');
    assert.deepEqual(errors, []);
    await context.close();

    const blockedContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await configure(blockedContext);
    await blockedContext.addInitScript(key => {
      const original = Storage.prototype.setItem;
      Storage.prototype.setItem = function (name, value) { if (name === key) throw new DOMException('blocked', 'SecurityError'); return original.call(this, name, value); };
    }, assistantKey);
    const blocked = await blockedContext.newPage();
    await blocked.goto(`${origin}/#assistant`, { waitUntil: 'networkidle' });
    await blocked.getByLabel('你想了解什么？').fill('室友作息不同怎样沟通？');
    await blocked.getByText('非实时 · 由站长整理', { exact: true }).waitFor();
    await blocked.getByRole('button', { name: '提交问题', exact: true }).click();
    await blocked.waitForFunction(() => document.querySelectorAll('.assistant-record').length === 1);
    assert.match(await blocked.locator('.assistant-storage-warning').innerText(), /本次页面/);
    await blocked.reload({ waitUntil: 'networkidle' });
    assert.equal(await blocked.locator('.assistant-record').count(), 0);
    await blockedContext.close();

    const offlineContext = await browser.newContext({ viewport: { width: 320, height: 844 } });
    await configure(offlineContext);
    await offlineContext.route('**/api/assistant/status', route => route.fulfill({ status: 404, json: { error: 'offline fixture' } }));
    const offline = await offlineContext.newPage();
    await offline.goto(`${origin}/#assistant`, { waitUntil: 'networkidle' });
    await offline.getByText('提交暂不可用 · 可保存本机草稿', { exact: true }).waitFor();
    await offline.getByLabel('你想了解什么？').fill('离线草稿');
    await offline.getByRole('button', { name: '提交问题', exact: true }).click();
    assert.match(await offline.locator('.assistant-feedback').innerText(), /未送达/);
    const draft = JSON.parse(await offline.evaluate(key => localStorage.getItem(key), assistantKey)).questions[0];
    assert.equal(draft.accessToken, undefined);
    assert.equal(await offline.locator('.assistant-answer').count(), 0);
    await offlineContext.close();
  } finally {
    await browser?.close();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    const inside = relative(privateRoot, directory);
    assert.ok(inside && !isAbsolute(inside) && inside !== '..' && !inside.startsWith(`..${sep}`) && inside.startsWith('assistant-browser-test-'));
    await rm(directory, { recursive: true, force: true });
  }
});
