import assert from 'node:assert/strict';
import test from 'node:test';
import { chromium } from 'playwright-core';
import { createRadarServer } from './serve-radar.mjs';

test('手机导航保留点击和键盘，并支持拖动确认、取消与竖向滚动', async () => {
  const server = await createRadarServer({ log: () => {} });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] });
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/`, { waitUntil: 'networkidle' });
    const nav = page.getByRole('navigation', { name: '手机主导航' });
    const buttons = nav.locator('button');
    const client = await page.context().newCDPSession(page);
    const center = async index => { const box = await buttons.nth(index).boundingBox(); return { x: box.x + box.width / 2, y: box.y + box.height / 2 }; };
    const touch = (type, point) => client.send('Input.dispatchTouchEvent', { type, touchPoints: point ? [{ ...point, id: 1 }] : [] });
    const selected = async index => { await page.waitForFunction(index => document.querySelectorAll('.mobile-nav button')[index].getAttribute('aria-current') === 'page', index, { timeout: 3000 }); };

    await buttons.nth(1).tap();
    await selected(1);
    await buttons.nth(0).click();
    await selected(0);
    const first = await center(0);
    const second = await center(1);
    const third = await center(2);
    await touch('touchStart', first);
    await touch('touchMove', await center(3));
    await page.locator('.mobile-nav.is-dragging').waitFor();
    await touch('touchEnd');
    await selected(3);
    await buttons.nth(1).tap();
    await selected(1);
    await buttons.nth(0).tap();
    await selected(0);
    await touch('touchStart', first);
    await touch('touchMove', { x: first.x + (second.x - first.x) * 1.65, y: first.y });
    await page.locator('.mobile-nav.is-dragging').waitFor();
    assert.equal(new URL(page.url()).hash, '#radar', '滑动途中不切换页面');
    const pill = await nav.locator('.mobile-nav-indicator').boundingBox();
    assert.ok(pill.x + pill.width / 2 > second.x && pill.x + pill.width / 2 < third.x, '选中块连续跟随手指');
    await touch('touchMove', third);
    await touch('touchEnd');
    await selected(2);
    assert.equal(new URL(page.url()).hash, '#saved', '松手后进入目标页，不回到起始按钮');
    await buttons.nth(1).tap();
    await selected(1);
    await buttons.nth(2).tap();
    await selected(2);

    await touch('touchStart', await center(2));
    await touch('touchMove', await center(3));
    await touch('touchCancel');
    await selected(2);
    assert.equal(await nav.evaluate(element => element.classList.contains('is-pressed')), false);
    await buttons.nth(1).tap();
    await selected(1);
    const vertical = await center(1);
    await touch('touchStart', vertical);
    await touch('touchMove', { x: vertical.x, y: vertical.y - 90 });
    await touch('touchEnd');
    await selected(1);
    assert.equal(await nav.evaluate(element => element.classList.contains('is-pressed')), false, '竖向滚动不会留下按压状态');

    const start = await center(1);
    const last = await center(3);
    const bounds = await nav.boundingBox();
    await page.mouse.move(start.x, start.y);
    await page.mouse.down();
    await page.mouse.move(last.x, last.y, { steps: 4 });
    await page.mouse.move(last.x, bounds.y - 60, { steps: 4 });
    await page.mouse.up();
    await selected(1);
    assert.equal(new URL(page.url()).hash, '#discover', '移出导航后取消，不误点起始按钮');
    await page.mouse.move(start.x, start.y);
    await page.mouse.down();
    await page.mouse.move(-30, start.y, { steps: 6 });
    await page.mouse.up();
    await selected(0);
    const left = await center(0);
    await page.mouse.move(left.x, left.y);
    await page.mouse.down();
    await page.mouse.move(430, left.y, { steps: 6 });
    await page.mouse.up();
    await selected(3);

    await buttons.nth(1).press('Enter');
    await selected(1);
    await buttons.nth(2).press('Space');
    await selected(2);
    await page.evaluate(() => { location.hash = 'profile'; });
    await selected(3);
    await page.reload({ waitUntil: 'networkidle' });
    await selected(3);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await touch('touchStart', await center(3));
    await page.locator('.mobile-nav.is-pressed').waitFor();
    const reduced = await nav.locator('.mobile-nav-indicator').evaluate(element => ({ transition: getComputedStyle(element).transitionDuration, scale: getComputedStyle(element).scale }));
    assert.equal(reduced.transition, '0s');
    assert.equal(reduced.scale, '1');
    await touch('touchCancel');
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
  }
});
